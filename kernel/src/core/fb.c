// one SGR parameter, already parsed out of the escape sequence
static void fb_ansi_apply(int code) {
    if (code == 0) {
        fg_color = 0x00FFFFFF;
        bg_color = 0x00000000;
        return;
    }  // reset
    if (code >= 30 && code <= 37) {
        fg_color = fb_ansi_color(code);
        return;
    }
    if (code >= 90 && code <= 97) {
        fg_color = fb_ansi_color(code);
        return;
    }
    if (code >= 40 && code <= 47) {
        bg_color = fb_ansi_color(code);
        return;
    }
    if (code >= 100 && code <= 107) {
        bg_color = fb_ansi_color(code);
        return;
    }
    // unrecognized code, ignore rather than guess
}

static void fb_put_pixel(struct limine_framebuffer *fb, size_t x, size_t y, uint32_t color) {
    if (x >= fb->width || y >= fb->height) return;
    volatile uint32_t *fb_ptr = (volatile uint32_t *)fb->address;
    fb_ptr[y * (fb->pitch / 4) + x] = color;
}

static void fb_draw_char(struct limine_framebuffer *fb, size_t x, size_t y, char c, uint32_t fg_color, uint32_t bg_color) {
    if ((unsigned char)c >= 128) return;
    const uint8_t *glyph = font_8x16[(unsigned char)c];
    for (size_t row = 0; row < FONT_HEIGHT; row++) {
        uint8_t byte = glyph[row];
        for (size_t col = 0; col < FONT_WIDTH; col++) {
            if ((byte >> (7 - col)) & 1) {
                fb_put_pixel(fb, x + col, y + row, fg_color);
            } else if (bg_color != 0) {
                fb_put_pixel(fb, x + col, y + row, bg_color);
            }
        }
    }
}

struct limine_framebuffer *fb;

static void fb_clear(uint32_t color) {
    if (!fb) return;
    volatile uint32_t *fb_ptr = (volatile uint32_t *)fb->address;
    size_t num_pixels = (fb->pitch / 4) * fb->height;
    for (size_t i = 0; i < num_pixels; i++) {
        fb_ptr[i] = color;
    }
}

void fb_init(struct limine_framebuffer_response *framebuffer_response) {
    fb = framebuffer_response->framebuffers[0];
    fb_clear(0x00000000);
}

static size_t cursor_x = 0;
static size_t cursor_y = 0;

static void terminal_scroll(void) {
    size_t line_bytes = FONT_HEIGHT * fb->pitch;
    size_t bytes_to_copy = (fb->height - FONT_HEIGHT) * fb->pitch;
    memmove(fb->address, (uint8_t *)fb->address + line_bytes, bytes_to_copy);
    size_t start_byte_offset = (fb->height - FONT_HEIGHT) * fb->pitch;
    size_t bottom_strip_bytes = FONT_HEIGHT * fb->pitch;
    memset((uint8_t *)fb->address + start_byte_offset, 0, bottom_strip_bytes);
    cursor_y = fb->height - FONT_HEIGHT;
}

void fb_terminal_print_char(char c) {
    switch (ansi_state) {
        case FB_ANSI_NORMAL:
            if (c == 0x1B) {
                ansi_state = FB_ANSI_ESC;
                return;
            }
            break;  // not an escape, fall through to the glyph-drawing code below
        case FB_ANSI_ESC:
            if (c == '[') {
                ansi_state = FB_ANSI_CSI;
                ansi_param = 0;
                return;
            }
            ansi_state = FB_ANSI_NORMAL;  // not a CSI sequence, bail out quietly
            return;
        case FB_ANSI_CSI:
            if (c >= '0' && c <= '9') {
                ansi_param = ansi_param * 10 + (c - '0');
                return;
            }
            if (c == ';') {
                fb_ansi_apply(ansi_param);
                ansi_param = 0;
                return;
            }
            if (c == 'm') {
                fb_ansi_apply(ansi_param);
                ansi_state = FB_ANSI_NORMAL;
                return;
            }
            ansi_state = FB_ANSI_NORMAL;  // unsupported final byte, bail out quietly
            return;
    }
    if (c == '\n') {
        cursor_x = 0;
        cursor_y += FONT_HEIGHT;
    } else {
        fb_draw_char(fb, cursor_x, cursor_y, c, fg_color, bg_color);
        cursor_x += FONT_WIDTH;
        if (cursor_x + FONT_WIDTH > fb->width) {
            cursor_x = 0;
            cursor_y += FONT_HEIGHT;
        }
    }
    if (cursor_y + FONT_HEIGHT > fb->height) {
        terminal_scroll();
    }
}

bool fb_is_active(void) {
    return fb != NULL;
}
